package ha

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"net"
	"net/netip"
	"net/url"
	"strings"
)

// Keepalived returns keepalived.conf for this node: VRRP over unicast (works
// where multicast does not, as in most virtual networks), both nodes BACKUP
// with nopreempt so the virtual IP stays where it is when a failed node
// returns, and a health check on the web port so the IP moves away from a
// node whose server stopped or lost ClickHouse.
func (n *Node) Keepalived(httpPort string) (string, error) {
	n.mu.Lock()
	c := n.cfg
	n.mu.Unlock()
	if !c.Enabled {
		return "", errors.New("high availability is not set up")
	}
	vip, err := netip.ParsePrefix(c.VIP)
	if err != nil {
		return "", errors.New("the virtual IP must include the prefix length")
	}
	self := interfaceIPv4(c.Interface)
	if self == "" {
		self = hostIP(c.SelfURL)
	}
	peer := hostIP(c.PeerURL)
	sum := sha256.Sum256([]byte("vrrp:" + c.Secret))
	pass := hex.EncodeToString(sum[:])[:8]
	if httpPort == "" {
		httpPort = "8080"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# keepalived.conf for UniFi Syslog Server node %q, generated by the server.\n", c.NodeName)
	b.WriteString("global_defs {\n    enable_script_security\n    script_user root\n}\n\n")
	fmt.Fprintf(&b, "vrrp_script uss_health {\n    script \"/usr/bin/curl -fsk -m 3 -o /dev/null http://127.0.0.1:%s/api/health\"\n    interval 3\n    fall 3\n    rise 2\n}\n\n", httpPort)
	b.WriteString("vrrp_instance UNIFY_SYSLOG {\n    state BACKUP\n    nopreempt\n")
	fmt.Fprintf(&b, "    interface %s\n    virtual_router_id %d\n    priority %d\n    advert_int 1\n", c.Interface, c.RouterID, c.Priority)
	if self != "" {
		fmt.Fprintf(&b, "    unicast_src_ip %s\n", self)
	}
	if peer != "" {
		fmt.Fprintf(&b, "    unicast_peer {\n        %s\n    }\n", peer)
	} else {
		b.WriteString("    # unicast_peer is added once the second node has joined.\n")
	}
	fmt.Fprintf(&b, "    authentication {\n        auth_type PASS\n        auth_pass %s\n    }\n", pass)
	fmt.Fprintf(&b, "    virtual_ipaddress {\n        %s dev %s\n    }\n", vip.String(), c.Interface)
	b.WriteString("    track_script {\n        uss_health\n    }\n}\n")
	return b.String(), nil
}

func hostIP(u string) string {
	p, err := url.Parse(u)
	if err != nil {
		return ""
	}
	h := p.Hostname()
	if a, err := netip.ParseAddr(h); err == nil {
		return a.String()
	}
	if ips, err := net.LookupIP(h); err == nil {
		for _, ip := range ips {
			if ip.To4() != nil {
				return ip.String()
			}
		}
	}
	return ""
}

// interfaceIPv4 is the first IPv4 address of an interface.
func interfaceIPv4(name string) string {
	ifc, err := net.InterfaceByName(name)
	if err != nil {
		return ""
	}
	addrs, err := ifc.Addrs()
	if err != nil {
		return ""
	}
	for _, a := range addrs {
		if ipn, ok := a.(*net.IPNet); ok && ipn.IP.To4() != nil {
			return ipn.IP.String()
		}
	}
	return ""
}

// Interfaces lists this machine's network interfaces with an IPv4 address,
// for the interface choice.
func Interfaces() []string {
	out := []string{}
	ifs, err := net.Interfaces()
	if err != nil {
		return out
	}
	for _, i := range ifs {
		if i.Flags&net.FlagLoopback != 0 {
			continue
		}
		if interfaceIPv4(i.Name) != "" {
			out = append(out, i.Name)
		}
	}
	return out
}
